"""Cogu joystick (velocity-tracking) locomotion environment for MuJoCo Playground / MJX.

Modelled on the Playground biped envs (Berkeley Humanoid joystick) and Open Duck Playground:
observations are what the real robot will have (IMU gyro + gravity direction, joint positions
and velocities, last action, gait phase, velocity command); rewards track a commanded planar
velocity and penalise torque, jerky actions, bad posture and falls. The model is the MJX variant
generated by `cad/export.py` (`build/mjcf/cogu_lower_body_mjx.xml`) — never edit it by hand.

Joint order (actuators, MJCF): L_hip_yaw, L_hip_roll, L_hip_pitch, L_knee, L_ankle, then the same
for R. Actions are offsets (× action_scale, radians) added to the `rest` keyframe pose and sent to
the position actuators, through a low-pass filter (`action_filter_alpha`: the servos get an
exponential moving average of the actions, so the policy cannot "walk" by vibrating its legs at
10+ Hz) and a per-episode random delay (actuator latency).

Environment configs travel with the checkpoints: train.py writes `env_config.json` next to them and
`config_for_checkpoint()` reads it back, so play.py / rollout.py / compare.py rebuild the exact
dynamics a policy was trained with (checkpoints without the file are pre-filter: alpha = 1).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, Optional, Union

import json

import jax
import jax.numpy as jp
import mujoco
import numpy as np
from ml_collections import config_dict
from mujoco import mjx
from mujoco.mjx._src import math as mjx_math
from mujoco_playground._src import gait, mjx_env

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_XML = REPO_ROOT / "build" / "mjcf" / "cogu_lower_body_mjx.xml"

FEET_SITES = ("L_foot_site", "R_foot_site")
FEET_GEOMS = ("L_foot_sole", "R_foot_sole")
ROOT_BODY = "pelvis"
JOINT_NAMES = tuple(f"{s}_{j}" for s in ("L", "R") for j in ("hip_yaw", "hip_roll", "hip_pitch", "knee", "ankle"))


def default_config() -> config_dict.ConfigDict:
    return config_dict.create(
        ctrl_dt=0.02,                 # 50 Hz policy, like the Pi runtime
        sim_dt=0.002,
        episode_length=500,           # 10 s
        action_repeat=1,
        action_scale=0.4,             # rad per unit action around the rest pose
        action_filter_alpha=0.4,      # target = EMA of actions: passes ~85 % of a 1.75 Hz step, ~30 % of 12 Hz jitter
        soft_joint_pos_limit_factor=0.9,
        max_action_delay_steps=2,     # 0..40 ms of actuator latency, sampled per episode
        noise_config=config_dict.create(
            level=1.0,
            scales=config_dict.create(joint_pos=0.02, joint_vel=1.0, gravity=0.05, gyro=0.2),
        ),
        reward_config=config_dict.create(
            scales=config_dict.create(
                # tracking
                tracking_lin_vel=1.5,
                tracking_ang_vel=0.8,
                # base motion / posture
                lin_vel_z=-0.5,
                ang_vel_xy=-0.05,
                orientation=-2.0,
                base_height=-5.0,
                # energy / smoothness
                torques=-0.02,
                action_rate=-0.1,         # v0/v1: -0.01 — they learned to vibrate at 12.6 Hz
                action_acc=-0.05,         # 2nd difference of the actions: grows with frequency^4
                # feet
                feet_air_time=2.0,        # v0/v1: 1.0
                feet_slip=-0.5,           # v0/v1: -0.1 (feet slid at half the body speed)
                feet_phase=1.5,           # v0/v1: 0.5
                feet_height=-1.0,         # new: swing apex below max_foot_height is penalised at touchdown
                feet_planted=-1.0,        # new: a foot on the floor > max_contact_time while walking (v3 limped)
                # misc
                termination=-1.0,
                stand_still=-1.0,         # v4: -0.3 — it kept marching in place on a zero command
                feet_air_still=-1.0,      # new: a foot off the floor on a zero command
                dof_pos_limits=-1.0,
                pose=-0.3,
            ),
            tracking_sigma=0.02,      # (m/s)²; v4: 0.05 — a 0.1 m/s miss still paid 0.82, so sideways and
                                      # backward commands were half-followed
            tracking_sigma_ang=0.2,   # (rad/s)²; v4: 0.5 (10 × tracking_sigma)
            max_foot_height=0.025,    # swing apex (m)
            feet_air_time_range=[0.15, 0.4],   # s; v0/v1: 0.1–0.35
            max_contact_time=0.5,     # s; at 1.5–2 Hz each foot should lift at least every ~0.6 s
            base_height_target=0.20,  # rest pelvis height is 0.205 m
        ),
        push_config=config_dict.create(enable=True, interval_range=[3.0, 6.0], magnitude_range=[0.05, 0.3]),
        gait_freq_range=[1.5, 2.0],   # Hz
        stand_phase_reset=True,       # zero command: the gait phase holds its start value (both feet down);
                                      # checkpoints up to v4 kept it running (config_for_checkpoint)
        command_resample_steps=250,   # 5 s
        lin_vel_x=[-0.10, 0.30],
        lin_vel_y=[-0.10, 0.10],
        ang_vel_yaw=[-1.0, 1.0],
        impl="jax",                   # CPU / Metal; "warp" needs CUDA
        naconmax=None,
        njmax=None,
    )


ENV_CONFIG_FILE = "env_config.json"


def save_config(cfg: config_dict.ConfigDict, out_dir: Union[str, Path]) -> Path:
    path = Path(out_dir) / ENV_CONFIG_FILE
    path.write_text(cfg.to_json(indent=2))
    return path


def config_for_checkpoint(ckpt: Union[str, Path]) -> config_dict.ConfigDict:
    """The env config a checkpoint was trained with (env_config.json in the step dir or its parent).
    Checkpoints from before the file existed (v0, v1) used no action filter."""
    ckpt = Path(ckpt)
    for d in (ckpt, ckpt.parent):
        f = d / ENV_CONFIG_FILE
        if f.exists():
            saved = json.loads(f.read_text())
            cfg = default_config()
            cfg.update(config_dict.ConfigDict(saved))
            if "stand_phase_reset" not in saved:      # trained before it existed
                cfg.stand_phase_reset = False
            return cfg
    cfg = default_config()
    cfg.action_filter_alpha = 1.0
    cfg.stand_phase_reset = False
    return cfg


class CoguJoystick(mjx_env.MjxEnv):
    """Track a (vx, vy, yaw-rate) command from the `rest` keyframe."""

    def __init__(
        self,
        xml_path: Union[str, Path] = DEFAULT_XML,
        config: config_dict.ConfigDict = default_config(),
        config_overrides: Optional[Dict[str, Union[str, int, list[Any]]]] = None,
    ):
        super().__init__(config, config_overrides)
        xml_path = Path(xml_path)
        if not xml_path.exists():
            raise FileNotFoundError(
                f"{xml_path} not found. Generate it with `uv run python -m cad.export --out build`.")
        self._xml_path = str(xml_path)
        self._mj_model = mujoco.MjModel.from_xml_path(self._xml_path)
        self._mj_model.opt.timestep = self.sim_dt
        self._mjx_model = mjx.put_model(self._mj_model, impl=self._config.impl)
        self._post_init()

    # ------------------------------------------------------------------ setup
    def _post_init(self) -> None:
        m = self._mj_model
        key = m.keyframe("rest")
        self._init_q = jp.array(key.qpos)
        self._default_pose = jp.array(key.qpos[7:])
        self._nu = m.nu
        self._lowers, self._uppers = m.jnt_range[1:].T
        c = (self._lowers + self._uppers) / 2
        r = self._uppers - self._lowers
        f = self._config.soft_joint_pos_limit_factor
        self._soft_lowers = jp.array(c - 0.5 * r * f)
        self._soft_uppers = jp.array(c + 0.5 * r * f)
        # pose cost weights: keep yaw/roll near rest, let pitch/knee move, ankle in between
        self._pose_weights = jp.array([1.0, 1.0, 0.02, 0.02, 0.3] * 2)
        self._hip_indices = jp.array([0, 1, 5, 6])
        self._torso_body_id = m.body(ROOT_BODY).id
        self._imu_site_id = m.site("imu").id
        self._feet_site_id = np.array([m.site(n).id for n in FEET_SITES])
        self._floor_geom_id = m.geom("floor").id
        self._feet_geom_id = np.array([m.geom(n).id for n in FEET_GEOMS])
        self._feet_found_adr = np.array([m.sensor_adr[m.sensor(f"{g}_floor_found").id] for g in FEET_GEOMS])
        self._feet_linvel_adr = jp.array([
            list(range(m.sensor_adr[s], m.sensor_adr[s] + 3))
            for s in (m.sensor(f"{side}_foot_global_linvel").id for side in ("L", "R"))])
        self._qpos_noise_scale = jp.full((self._nu,), self._config.noise_config.scales.joint_pos)

    # --------------------------------------------------------------- sensors
    def _sensor(self, data: mjx.Data, name: str) -> jax.Array:
        return mjx_env.get_sensor_data(self._mj_model, data, name)

    def get_upvector(self, data):      return self._sensor(data, "upvector")        # pelvis z-axis, world frame
    def get_gyro(self, data):          return self._sensor(data, "gyro")
    def get_accelerometer(self, data): return self._sensor(data, "accelerometer")
    def get_local_linvel(self, data):  return self._sensor(data, "local_linvel")
    def get_global_linvel(self, data): return self._sensor(data, "global_linvel")
    def get_global_angvel(self, data): return self._sensor(data, "global_angvel")

    def get_gravity(self, data: mjx.Data) -> jax.Array:
        """Gravity direction in the IMU frame (what an IMU orientation filter gives)."""
        return data.site_xmat[self._imu_site_id].T @ jp.array([0.0, 0.0, -1.0])

    def _feet_contact(self, data: mjx.Data) -> jax.Array:
        return data.sensordata[self._feet_found_adr] > 0

    # ----------------------------------------------------------------- reset
    def reset(self, rng: jax.Array) -> mjx_env.State:
        qpos = self._init_q
        qvel = jp.zeros(self.mjx_model.nv)

        rng, k1, k2, k3, k4 = jax.random.split(rng, 5)
        qpos = qpos.at[0:2].set(qpos[0:2] + jax.random.uniform(k1, (2,), minval=-0.3, maxval=0.3))
        yaw = jax.random.uniform(k2, (1,), minval=-jp.pi, maxval=jp.pi)
        quat = mjx_math.axis_angle_to_quat(jp.array([0.0, 0.0, 1.0]), yaw)
        qpos = qpos.at[3:7].set(mjx_math.quat_mul(qpos[3:7], quat))
        qpos = qpos.at[7:].set(qpos[7:] + jax.random.uniform(k3, (self._nu,), minval=-0.05, maxval=0.05))
        qvel = qvel.at[0:6].set(jax.random.uniform(k4, (6,), minval=-0.2, maxval=0.2))

        data = mjx_env.make_data(self.mj_model, qpos=qpos, qvel=qvel, ctrl=self._default_pose,
                                 impl=self.mjx_model.impl.value, naconmax=self._config.naconmax,
                                 njmax=self._config.njmax)
        data = mjx.forward(self.mjx_model, data)

        rng, k_gait, k_cmd, k_push, k_delay = jax.random.split(rng, 5)
        gait_freq = jax.random.uniform(k_gait, (1,), minval=self._config.gait_freq_range[0],
                                       maxval=self._config.gait_freq_range[1])
        phase_dt = 2 * jp.pi * self.dt * gait_freq
        phase = jp.array([0.0, jp.pi])
        push_interval = jax.random.uniform(k_push, minval=self._config.push_config.interval_range[0],
                                           maxval=self._config.push_config.interval_range[1])
        push_interval_steps = jp.round(push_interval / self.dt).astype(jp.int32)
        n_delay = self._config.max_action_delay_steps
        delay = jax.random.randint(k_delay, (), 0, n_delay + 1)

        info = {
            "rng": rng,
            "step": 0,
            "command": self.sample_command(k_cmd),
            "last_act": jp.zeros(self._nu),
            "last_last_act": jp.zeros(self._nu),
            "action_filtered": jp.zeros(self._nu),
            "motor_targets": self._default_pose,
            "ctrl_history": jp.tile(self._default_pose, (n_delay + 1, 1)),
            "action_delay": delay,
            "feet_air_time": jp.zeros(2),
            "feet_contact_time": jp.zeros(2),
            "last_contact": jp.zeros(2, dtype=bool),
            "swing_peak": jp.zeros(2),
            "phase_dt": phase_dt,
            "phase": phase,
            "push": jp.zeros(2),
            "push_step": 0,
            "push_interval_steps": push_interval_steps,
        }
        metrics = {f"reward/{k}": jp.zeros(()) for k in self._config.reward_config.scales.keys()}
        metrics["swing_peak"] = jp.zeros(())
        metrics["forward_speed"] = jp.zeros(())

        contact = self._feet_contact(data)
        obs = self._get_obs(data, info, contact)
        reward, done = jp.zeros(2)
        return mjx_env.State(data, obs, reward, done, metrics, info)

    # ------------------------------------------------------------------ step
    def step(self, state: mjx_env.State, action: jax.Array) -> mjx_env.State:
        cfg = self._config
        state.info["rng"], push1, push2 = jax.random.split(state.info["rng"], 3)
        push_theta = jax.random.uniform(push1, maxval=2 * jp.pi)
        push_mag = jax.random.uniform(push2, minval=cfg.push_config.magnitude_range[0],
                                      maxval=cfg.push_config.magnitude_range[1])
        push = jp.array([jp.cos(push_theta), jp.sin(push_theta)])
        push *= jp.mod(state.info["push_step"] + 1, state.info["push_interval_steps"]) == 0
        push *= cfg.push_config.enable
        qvel = state.data.qvel
        qvel = qvel.at[:2].set(push * push_mag + qvel[:2])
        state = state.replace(data=state.data.replace(qvel=qvel))

        # action -> low-pass filter -> position target -> (randomised) actuator latency
        a = cfg.action_filter_alpha
        filtered = a * action + (1.0 - a) * state.info["action_filtered"]
        state.info["action_filtered"] = filtered
        motor_targets = self._default_pose + filtered * cfg.action_scale
        motor_targets = jp.clip(motor_targets, self._lowers, self._uppers)
        hist = jp.roll(state.info["ctrl_history"], 1, axis=0).at[0].set(motor_targets)
        applied = hist[state.info["action_delay"]]
        data = mjx_env.step(self.mjx_model, state.data, applied, self.n_substeps)
        state.info["ctrl_history"] = hist
        state.info["motor_targets"] = applied

        contact = self._feet_contact(data)
        contact_filt = contact | state.info["last_contact"]
        first_contact = (state.info["feet_air_time"] > 0.0) * contact_filt
        state.info["feet_air_time"] += self.dt
        state.info["feet_contact_time"] = (state.info["feet_contact_time"] + self.dt) * contact
        p_fz = data.site_xpos[self._feet_site_id][..., -1]
        state.info["swing_peak"] = jp.maximum(state.info["swing_peak"], p_fz)

        obs = self._get_obs(data, state.info, contact)
        done = self._get_termination(data)

        rewards = self._get_reward(data, action, state.info, done, first_contact, contact)
        rewards = {k: v * cfg.reward_config.scales[k] for k, v in rewards.items()}
        reward = jp.clip(sum(rewards.values()) * self.dt, 0.0, 10000.0)

        state.info["push"] = push
        state.info["step"] += 1
        state.info["push_step"] += 1
        phase_tp1 = state.info["phase"] + state.info["phase_dt"]
        phase_tp1 = jp.fmod(phase_tp1 + jp.pi, 2 * jp.pi) - jp.pi
        if cfg.stand_phase_reset:                     # standing: hold the start phase (both feet down)
            moving = jp.linalg.norm(state.info["command"]) > 0.05
            phase_tp1 = jp.where(moving, phase_tp1, jp.array([0.0, jp.pi]))
        state.info["phase"] = phase_tp1
        state.info["last_last_act"] = state.info["last_act"]
        state.info["last_act"] = action
        state.info["rng"], cmd_rng = jax.random.split(state.info["rng"])
        resample = state.info["step"] > cfg.command_resample_steps
        state.info["command"] = jp.where(resample, self.sample_command(cmd_rng), state.info["command"])
        state.info["step"] = jp.where(done | resample, 0, state.info["step"])
        state.info["feet_air_time"] *= ~contact
        state.info["last_contact"] = contact
        state.info["swing_peak"] *= ~contact
        for k, v in rewards.items():
            state.metrics[f"reward/{k}"] = v
        state.metrics["swing_peak"] = jp.mean(state.info["swing_peak"])
        state.metrics["forward_speed"] = self.get_local_linvel(data)[0]

        done = done.astype(reward.dtype)
        return state.replace(data=data, obs=obs, reward=reward, done=done)

    def _get_termination(self, data: mjx.Data) -> jax.Array:
        tilted = self.get_upvector(data)[-1] < 0.5          # > 60° from vertical
        too_low = data.qpos[2] < 0.10                        # pelvis near the ground
        return tilted | too_low | jp.isnan(data.qpos).any() | jp.isnan(data.qvel).any()

    # ----------------------------------------------------------- observation
    def _get_obs(self, data: mjx.Data, info: dict[str, Any], contact: jax.Array) -> mjx_env.Observation:
        noise = self._config.noise_config

        def noisy(x, scale):
            info["rng"], k = jax.random.split(info["rng"])
            return x + (2 * jax.random.uniform(k, shape=x.shape) - 1) * noise.level * scale

        gyro = self.get_gyro(data)
        gravity = self.get_gravity(data)
        joint_angles = data.qpos[7:]
        joint_vel = data.qvel[6:]
        phase = jp.concatenate([jp.cos(info["phase"]), jp.sin(info["phase"])])

        state = jp.hstack([
            noisy(gyro, noise.scales.gyro),                                   # 3
            noisy(gravity, noise.scales.gravity),                             # 3
            info["command"],                                                  # 3
            noisy(joint_angles, self._qpos_noise_scale) - self._default_pose,  # 10
            noisy(joint_vel, noise.scales.joint_vel),                         # 10
            info["last_act"],                                                 # 10
            phase,                                                            # 4
        ])
        privileged_state = jp.hstack([
            state,
            gyro, self.get_accelerometer(data), gravity,
            self.get_local_linvel(data), self.get_global_angvel(data),
            joint_angles - self._default_pose, joint_vel,
            data.qpos[2],                                                     # root height
            data.actuator_force,                                              # 10
            contact,                                                          # 2
            data.sensordata[self._feet_linvel_adr].ravel(),                   # 6
            info["feet_air_time"],                                            # 2
            info["action_delay"].astype(jp.float32)[None],                    # 1
        ])
        return {"state": state, "privileged_state": privileged_state}

    # ---------------------------------------------------------------- reward
    def _get_reward(self, data, action, info, done, first_contact, contact) -> dict[str, jax.Array]:
        cmd = info["command"]
        qpos = data.qpos[7:]
        return {
            "tracking_lin_vel": self._reward_tracking_lin_vel(cmd, self.get_local_linvel(data)),
            "tracking_ang_vel": self._reward_tracking_ang_vel(cmd, self.get_gyro(data)),
            "lin_vel_z": jp.square(self.get_global_linvel(data)[2]),
            "ang_vel_xy": jp.sum(jp.square(self.get_global_angvel(data)[:2])),
            "orientation": jp.sum(jp.square(self.get_upvector(data)[:2])),
            "base_height": jp.square(data.qpos[2] - self._config.reward_config.base_height_target),
            "torques": jp.sum(jp.abs(data.actuator_force)),
            "action_rate": jp.sum(jp.square(action - info["last_act"])),
            "action_acc": jp.sum(jp.square(action - 2.0 * info["last_act"] + info["last_last_act"])),
            "feet_air_time": self._reward_feet_air_time(info["feet_air_time"], first_contact, cmd),
            "feet_slip": self._cost_feet_slip(data, contact),
            "feet_phase": self._reward_feet_phase(data, info["phase"], cmd),
            "feet_height": self._cost_feet_height(info["swing_peak"], first_contact, cmd),
            "feet_planted": self._cost_feet_planted(info["feet_contact_time"], cmd),
            # cast: a raw bool here makes XLA-CPU compile a ~3x slower step (measured)
            "termination": done.astype(jp.float32),
            "stand_still": jp.sum(jp.abs(qpos - self._default_pose)) * (jp.linalg.norm(cmd) < 0.05),
            "feet_air_still": jp.sum(~contact).astype(jp.float32) * (jp.linalg.norm(cmd) < 0.05),
            "dof_pos_limits": self._cost_joint_pos_limits(qpos),
            "pose": jp.sum(jp.square(qpos - self._default_pose) * self._pose_weights),
        }

    def _reward_tracking_lin_vel(self, cmd, local_vel):
        err = jp.sum(jp.square(cmd[:2] - local_vel[:2]))
        return jp.exp(-err / self._config.reward_config.tracking_sigma)

    def _reward_tracking_ang_vel(self, cmd, ang_vel):
        err = jp.square(cmd[2] - ang_vel[2])
        return jp.exp(-err / self._config.reward_config.tracking_sigma_ang)

    def _cost_joint_pos_limits(self, qpos):
        out = -jp.clip(qpos - self._soft_lowers, None, 0.0) + jp.clip(qpos - self._soft_uppers, 0.0, None)
        return jp.sum(out)

    def _cost_feet_slip(self, data, contact):
        feet_vel = data.sensordata[self._feet_linvel_adr][..., :2]
        return jp.sum(jp.linalg.norm(feet_vel, axis=-1) * contact)

    def _reward_feet_air_time(self, air_time, first_contact, cmd):
        t_min, t_max = self._config.reward_config.feet_air_time_range
        reward = jp.sum(jp.clip((air_time - t_min) * first_contact, max=t_max - t_min))
        return reward * (jp.linalg.norm(cmd) > 0.05)

    def _cost_feet_planted(self, contact_time, cmd):
        """Seconds (capped at 1) each foot has stayed on the floor beyond max_contact_time, while asked to move.
        Without it the v3 policy kept the right foot planted and tapped the left one."""
        over = jp.clip(contact_time - self._config.reward_config.max_contact_time, 0.0, 1.0)
        return jp.sum(over) * (jp.linalg.norm(cmd) > 0.05)

    def _cost_feet_height(self, swing_peak, first_contact, cmd):
        """At each touchdown, how far the swing apex stayed below max_foot_height (squared, relative)."""
        short = jp.clip(1.0 - swing_peak / self._config.reward_config.max_foot_height, 0.0, None)
        return jp.sum(jp.square(short) * first_contact) * (jp.linalg.norm(cmd) > 0.05)

    def _reward_feet_phase(self, data, phase, cmd):
        foot_z = data.site_xpos[self._feet_site_id][..., -1]
        rz = gait.get_rz(phase, swing_height=self._config.reward_config.max_foot_height)
        err = jp.sum(jp.square(foot_z - rz))
        return jp.exp(-err / 0.0005) * (jp.linalg.norm(cmd) > 0.05)

    # --------------------------------------------------------------- command
    def sample_command(self, rng: jax.Array) -> jax.Array:
        k1, k2, k3, k4 = jax.random.split(rng, 4)
        c = self._config
        vx = jax.random.uniform(k1, minval=c.lin_vel_x[0], maxval=c.lin_vel_x[1])
        vy = jax.random.uniform(k2, minval=c.lin_vel_y[0], maxval=c.lin_vel_y[1])
        wz = jax.random.uniform(k3, minval=c.ang_vel_yaw[0], maxval=c.ang_vel_yaw[1])
        return jp.where(jax.random.bernoulli(k4, p=0.1), jp.zeros(3), jp.hstack([vx, vy, wz]))

    # ------------------------------------------------------------- accessors
    @property
    def xml_path(self) -> str:
        return self._xml_path

    @property
    def action_size(self) -> int:
        return self._nu

