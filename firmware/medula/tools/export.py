"""Write the medula firmware's generated headers from the simulator: the policies' weights and every constant and
table the controllers need, read from the same Python objects the simulator runs (play.Sim2Sim, GetupPolicy,
PosePolicy, medula.py), so the C++ and the Python cannot drift apart.

    uv run python firmware/medula/tools/export.py            # -> firmware/medula/gen/cogu_policies.h, cogu_params.h
    uv run python firmware/medula/tools/export.py --check    # and compare a NumPy rebuild of each MLP with the JAX one

The walker is walk v10, the get-up is get-up v8 (the checkpoints the brain uses, sim/brain/pet.py); sit and lie down
are the scripted reference (no policy), as in the simulator.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
GEN = HERE.parent / "gen"
sys.path.insert(0, str(ROOT / "sim" / "playground"))
sys.path.insert(0, str(ROOT / "sim" / "brain"))

WALK = ROOT / "sim" / "playground" / "checkpoints" / "cogu_walk_v10"
GETUP = ROOT / "sim" / "playground" / "checkpoints" / "cogu_getup_v8"


def mlp_params(ckpt: Path) -> dict:
    """The actor of a brax PPO checkpoint as plain arrays: observation mean / std, the layers, and how the output
    becomes the action (tanh of the mean for tanh_normal, the mean itself for normal)."""
    import json

    import jax_compat  # noqa: F401
    from brax.training import checkpoint as bc

    cfg = json.loads((ckpt / "ppo_network_config.json").read_text())
    kw = cfg["network_factory_kwargs"]
    assert kw["activation"] == "silu", kw["activation"]
    norm, pol, _ = bc.load(ckpt.resolve())
    p = pol["params"]
    if "MLP_0" in p:                                       # separate std: the hidden MLP, then a Dense for the mean
        names = sorted(p["MLP_0"], key=lambda k: int(k.split("_")[1]))
        layers = [p["MLP_0"][n] for n in names] + [p["Dense_0"]]
    else:                                                  # one MLP whose last layer is mean and std together
        names = sorted(p, key=lambda k: int(k.split("_")[1]))
        layers = [p[n] for n in names]
    n_act = cfg["action_size"]
    ws = [np.asarray(lay["kernel"], np.float32) for lay in layers]
    bs = [np.asarray(lay["bias"], np.float32) for lay in layers]
    ws[-1], bs[-1] = ws[-1][:, :n_act], bs[-1][:n_act]     # the mean only
    return dict(mean=np.asarray(norm.mean["state"], np.float32), std=np.asarray(norm.std["state"], np.float32),
                ws=ws, bs=bs, tanh=kw["distribution_type"] == "tanh_normal", n_obs=ws[0].shape[0], n_act=n_act,
                n_priv=cfg["observation_size"]["privileged_state"]["shape"][0])


def mlp_numpy(P: dict, obs: np.ndarray) -> np.ndarray:
    x = (obs.astype(np.float32) - P["mean"]) / P["std"]
    for i, (w, b) in enumerate(zip(P["ws"], P["bs"])):
        x = x @ w + b
        if i < len(P["ws"]) - 1:
            x = x / (1.0 + np.exp(-x))                     # silu
    return np.tanh(x) if P["tanh"] else x


def fl(v) -> str:
    """A C float literal (always with a point or an exponent)."""
    s = f"{float(np.float32(v)):.9g}"
    return (s if any(c in s for c in ".en") else s + ".0") + "f"


def c_floats(name: str, a: np.ndarray) -> str:
    flat = np.asarray(a, np.float32).ravel()
    rows = [", ".join(fl(v) for v in flat[i:i + 8]) for i in range(0, flat.size, 8)]
    return f"static const float {name}[{flat.size}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def c_doubles(name: str, a: np.ndarray) -> str:
    flat = np.asarray(a, float).ravel()
    return f"static const double {name}[{flat.size}] = {{" + ", ".join(repr(float(v)) for v in flat) + "};\n"


def policy_header(policies: dict) -> str:
    out = ["// Generated by firmware/medula/tools/export.py from the simulator's checkpoints. Do not edit.",
           "#pragma once", "#include \"mlp.h\"", "", "namespace cogu {", ""]
    for name, (P, src) in policies.items():
        out.append(f"// {name}: {src}")
        sizes = [P["n_obs"]] + [w.shape[1] for w in P["ws"]]
        out.append(c_floats(f"{name}_mean", P["mean"]))
        out.append(c_floats(f"{name}_inv_std", 1.0 / P["std"]))
        for i, (w, b) in enumerate(zip(P["ws"], P["bs"])):
            out.append(c_floats(f"{name}_w{i}", w.T))      # row-major [out][in]: each output is one dot product
            out.append(c_floats(f"{name}_b{i}", b))
        out.append(f"static const int {name}_sizes[{len(sizes)}] = {{{', '.join(map(str, sizes))}}};")
        ws = ", ".join(f"{name}_w{i}" for i in range(len(P["ws"])))
        bs = ", ".join(f"{name}_b{i}" for i in range(len(P["bs"])))
        out.append(f"static const float* const {name}_ws[] = {{{ws}}};")
        out.append(f"static const float* const {name}_bs[] = {{{bs}}};")
        out.append(f"static const MlpSpec {name.upper()}_POLICY = {{{len(P['ws'])}, {name}_sizes, {name}_mean, "
                   f"{name}_inv_std, {name}_ws, {name}_bs, {'true' if P['tanh'] else 'false'}}};")
        out.append("")
    out.append("}  // namespace cogu")
    return "\n".join(out) + "\n"


def params_header(sim, getup, pose) -> str:
    import cogu_pose
    import medula

    w, g, p = sim.cfg, getup.cfg, pose.cfg
    rc, ref = w.recover, g.reference
    assert ref.enable and ref.roll and not ref.get("throw", False) and not ref.scripted_residual, "get-up v8 layout"
    assert not getup.cfg.full_range_actions
    assert pose.policy is None
    nu = sim.m.nu
    K = getup.roll_keys.shape[1]

    def arr(name, a):
        return c_floats(name, a)

    f = fl

    lines = ["// Generated by firmware/medula/tools/export.py from the simulator's configs. Do not edit.",
             "#pragma once", "", "namespace cogu {", "",
             f"constexpr int NU = {nu};                       // leg joints: L yaw roll pitch knee ankle, then R",
             f"constexpr float DT = {f(sim.dt)};              // control step (s)",
             f"constexpr double DT_S = {float(sim.dt)!r};             // the same in double: every timer adds it in double, as"
             " the Python does (in float, 15 x 0.02 falls short of 0.3)",
             "",
             "// medula.py: the medula's own rules",
             f"constexpr double WATCHDOG = {float(medula.WATCHDOG)!r};",
             f"constexpr float RAMP[3] = {{{', '.join(f(x) for x in medula.RAMP)}}};",
             f"constexpr float LIMIT_LO[3] = {{{', '.join(f(x) for x in medula.LIMITS[:, 0])}}};",
             f"constexpr float LIMIT_HI[3] = {{{', '.join(f(x) for x in medula.LIMITS[:, 1])}}};",
             f"constexpr float LOW_VOLTS = {f(medula.LOW)}, CUTOFF_VOLTS = {f(medula.CUTOFF)};",
             "",
             "// the joints (the `rest` keyframe and the joint ranges of the MJCF)",
             arr("DEFAULT_POSE", sim.default_pose), arr("JOINT_LO", sim.lowers), arr("JOINT_HI", sim.uppers),
             "// walk v10 (play.Sim2Sim)",
             f"constexpr float WALK_ALPHA = {f(w.action_filter_alpha)}, WALK_SCALE = {f(w.action_scale)};",
             f"constexpr float WALK_PHASE_DT = {f(sim.phase_dt)};",
             f"constexpr bool WALK_RECOVER = {'true' if rc.enable else 'false'}, "
             f"WALK_LATCH = {'true' if rc.get('latch', False) else 'false'};",
             f"constexpr float WALK_RECOVER_GYRO = {f(rc.gyro)}, WALK_RECOVER_COS_TILT = {f(np.cos(rc.tilt))};",
             f"constexpr double WALK_RECOVER_HOLD = {float(rc.hold)!r}, WALK_RECOVER_COOLDOWN = {float(rc.get('cooldown', 0.0))!r};",
             f"constexpr bool WALK_STAND_PHASE_RESET = {'true' if w.get('stand_phase_reset', False) else 'false'};",
             "",
             "// get-up v8 (play.GetupPolicy): the scripted catch along the tilt, relax + roll, the policy's correction",
             f"constexpr float GETUP_ALPHA = {f(g.action_filter_alpha)}, GETUP_RESIDUAL = {f(ref.residual_scale)};",
             f"constexpr float GETUP_LEAD = {f(ref.lead)}, GETUP_RATE = {f(ref.rate)};",
             f"constexpr float GETUP_LIE_TILT = {f(ref.lie_tilt)};",
             f"constexpr double GETUP_LIE_TIME = {float(ref.lie_time)!r}, GETUP_RELAX = {float(ref.relax_time)!r};",
             f"constexpr int GETUP_N_TILTS = {len(getup.ref_tilts)};",
             arr("GETUP_TILTS", getup.ref_tilts),
             arr("GETUP_LEGS", getup.ref_legs),                   # [tilt][5] rad
             f"constexpr int GETUP_ROLL_K = {K};",
             arr("GETUP_ROLL_KEYS", getup.roll_keys),             # [4 sides][K][NU]
             c_doubles("GETUP_ROLL_ENDS", getup.roll_ends),       # [4][K] s
             "",
             "// sit / lie down (play.PosePolicy with no checkpoint: the scripted reference, cogu_pose)",
             f"constexpr float POSE_ALPHA = {f(p.action_filter_alpha)};",
             f"constexpr double SIT_TIME = {float(p.sit.time)!r}, SIT_SPLIT = {float(p.sit.split)!r};",
             f"constexpr float REST_LEGS[3] = {{{', '.join(f(x) for x in cogu_pose.REST_LEGS)}}};   // lean, hip, knee (deg)",
             f"constexpr float SIT_CROUCH[3] = {{{', '.join(f(x) for x in p.sit.crouch)}}};",
             f"constexpr float SIT_SEAT[3] = {{{', '.join(f(x) for x in p.sit.seat)}}};",
             f"constexpr float SIT_CROUCH_TILT = {f(p.sit.crouch_pose[0])}, SIT_PELVIS_TILT = {f(p.sit.pelvis_tilt)};",
             f"constexpr float POSE_FALL_TILT = {f(p.reward_config.fall_tilt)};",
             f"constexpr float LIE_LEAD = {f(p.lie.lead)}, LIE_RATE = {f(p.lie.rate)}, LIE_END = {f(p.lie.end)};",
             f"constexpr float LIE_STRETCH[3] = {{{', '.join(f(np.radians(x)) for x in p.lie.stretch)}}};   // rad",
             f"constexpr float LIE_STRETCH_RATE = {f(p.lie.stretch_rate)};",
             f"constexpr int LIE_N_TILTS = {len(pose.lie_tilts)};",
             arr("LIE_TILTS", pose.lie_tilts),
             arr("LIE_LEGS", pose.lie_legs),                       # [tilt][3] rad
             "}  // namespace cogu", ""]
    return "\n".join(lines)


def build(check: bool) -> int:
    import play
    from rollout import latest_checkpoint, load_policy

    import pet

    walk, getup_ck = latest_checkpoint(WALK), latest_checkpoint(GETUP)
    sim = play.Sim2Sim(pet.APARTMENT_XML, walk, seed=0)
    getup = play.GetupPolicy(sim, getup_ck)
    pose = play.PosePolicy(sim, None)
    policies = {}
    for name, ck in (("walk", walk), ("getup", getup_ck)):
        src = f"{ck.relative_to(ROOT)}"
        policies[name] = (mlp_params(ck), src)
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "cogu_policies.h").write_text(policy_header(policies))
    (GEN / "cogu_params.h").write_text(params_header(sim, getup, pose))
    for name in ("cogu_policies.h", "cogu_params.h"):
        data = (GEN / name).read_bytes()
        print(f"  {name}: {len(data) / 1e3:.0f} kB, sha1 {hashlib.sha1(data).hexdigest()[:10]}")
    for name, (P, src) in policies.items():
        n = sum(w.size + b.size for w, b in zip(P["ws"], P["bs"]))
        print(f"  {name}: {P['n_obs']} -> {' -> '.join(str(w.shape[1]) for w in P['ws'])}, {n} weights "
              f"({n * 4 / 1e3:.0f} kB float32), {'tanh' if P['tanh'] else 'linear'} output, from {src}")
    if not check:
        return 0
    import jax
    import jax.numpy as jp

    rng = np.random.default_rng(0)
    ok = True
    for name, ck in (("walk", walk), ("getup", getup_ck)):
        P = policies[name][0]
        fn = jax.jit(load_policy(ck))
        obs = (P["mean"] + P["std"] * rng.standard_normal((256, P["n_obs"]))).astype(np.float32)
        ref = np.stack([np.asarray(fn({"state": jp.asarray(o), "privileged_state": jp.zeros(P["n_priv"])},
                                      jax.random.PRNGKey(0))[0]) for o in obs])
        err = float(np.max(np.abs(mlp_numpy(P, obs) - ref)))
        ok &= err < 1e-4
        print(f"  {name}: NumPy rebuild vs JAX, 256 observations: max |Δaction| {err:.1e}")
    return 0 if ok else 1


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    sys.exit(build(ap.parse_args().check))
